#!/bin/sh
# Writes THIRD_PARTY_NOTICES.md: the licence of every third-party module
# compiled into the blobfish binary, plus Go's own (its runtime and
# standard library are linked in too). MIT and BSD licences require these
# texts to travel with binary copies, so release archives and the Docker
# image include this file. CI fails if it is out of date.
set -eu
cd "$(dirname "$0")/.."
out=THIRD_PARTY_NOTICES.md
goroot=$(go env GOROOT)

section() { # heading licence-file [patents-file]
	printf '\n## %s\n\n```\n' "$1"
	cat "$2"
	if [ -n "${3:-}" ]; then printf '\n'; cat "$3"; fi
	printf '```\n'
}

{
	printf '# Third-party notices\n\n'
	printf 'The blobfish binary includes the software below. Each part keeps its\n'
	printf 'own licence; BlobFish itself is licensed under the Apache License 2.0\n'
	printf '(see LICENSE). Generated by scripts/third-party-notices.sh.\n'
	# No Go version in the heading: the text is the same across releases,
	# and CI may build with a newer patch release than the one on disk here.
	section "Go runtime and standard library" "$goroot/LICENSE" "$goroot/PATENTS"
	go list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}} {{.Dir}}{{end}}{{end}}' ./cmd/blobfish |
		sort -u | while read -r path version dir; do
			lic=""
			for f in "$dir"/LICENSE* "$dir"/COPYING*; do
				[ -f "$f" ] && { lic=$f; break; }
			done
			if [ -z "$lic" ]; then
				echo "no licence file found for $path $version" >&2
				exit 1
			fi
			pat=""
			[ -f "$dir/PATENTS" ] && pat="$dir/PATENTS"
			section "$path $version" "$lic" "$pat"
		done
} >"$out"
echo "wrote $out"
